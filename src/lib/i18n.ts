export const TRANSLATIONS: Record<LanguageCode, Dictionary> = { en, hi, mr };

export function isLanguageCode(value: string | undefined | null): value is LanguageCode {
  return value === "en" || value === "hi" || value === "mr";
}

export function translate(
  language: LanguageCode,
  key: string,
  overrides?: Record<string, string> | null,
): string {
  return overrides?.[key] || TRANSLATIONS[language]?.[key] || TRANSLATIONS.en[key] || key;
}

